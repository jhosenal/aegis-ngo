import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export interface TraceEntry { implementation: string[]; tests: string[]; gateTasks: string[] }
export type TraceMap = Record<string, TraceEntry>;
export type GateResult = 'PASS' | 'FAIL' | 'MISSING';
export type StatusWord = 'fixture-tested' | 'pending';
export interface TraceRow {
  requirement: string;
  entry: TraceEntry;
  gates: Array<{ gate: string; result: GateResult; evidence: string | null }>;
  status: StatusWord;
}

export const LIMITATIONS = [
  'Stub providers are not live; nothing here is live-tested.',
  'All data is synthetic.',
  'Demo storage is ephemeral.',
  'The hash chain is not a Merkle proof.',
  'Screenshots are not an accessibility audit.',
];

const EVIDENCE_NAME = /^AEG-EVD-(TSK-\d{3})_(\d{8}T\d{6}Z)\.md$/;

export function newestEvidence(evidenceDir: string, gate: string): { result: GateResult; evidence: string | null } {
  if (!existsSync(evidenceDir)) return { result: 'MISSING', evidence: null };
  const names = readdirSync(evidenceDir)
    .filter((name) => EVIDENCE_NAME.exec(name)?.[1] === gate)
    .sort();
  const newest = names[names.length - 1];
  if (newest === undefined) return { result: 'MISSING', evidence: null };
  const text = readFileSync(join(evidenceDir, newest), 'utf8');
  const line = /^\| Result \| \*\*(PASS|FAIL)\*\* \|/m.exec(text);
  return { result: line?.[1] === 'PASS' ? 'PASS' : 'FAIL', evidence: newest };
}

export function validateMap(map: TraceMap, root: string, knownGates: string[]): string[] {
  const problems: string[] = [];
  for (const [requirement, entry] of Object.entries(map)) {
    for (const file of [...entry.implementation, ...entry.tests]) {
      if (!existsSync(join(root, file))) problems.push(`${requirement}: unknown file ${file}`);
    }
    for (const gate of entry.gateTasks) {
      if (!knownGates.includes(gate)) problems.push(`${requirement}: unknown gate ${gate}`);
    }
  }
  return problems;
}

export function buildRows(map: TraceMap, evidenceDir: string): TraceRow[] {
  return Object.entries(map).map(([requirement, entry]) => {
    const gates = entry.gateTasks.map((gate) => ({ gate, ...newestEvidence(evidenceDir, gate) }));
    const covered = gates.length > 0 && gates.every((item) => item.result === 'PASS');
    return { requirement, entry, gates, status: covered ? 'fixture-tested' : 'pending' };
  });
}

export function renderReport(rows: TraceRow[]): string {
  const lines = [
    '# AEG-TRC-001 Traceability report',
    '',
    'Generated by `tools/trace.ts` from `tools/trace-map.json` and the newest evidence file per gate. A requirement is `fixture-tested` only when every listed gate has a PASS as its newest evidence; otherwise it is `pending`.',
    '',
    '| Requirement | Implementation | Tests | Latest gate results | Status |',
    '|---|---|---|---|---|',
  ];
  for (const row of rows) {
    const gates = row.gates.map((item) => `${item.gate}: ${item.result}`).join('; ');
    lines.push(`| ${row.requirement} | ${row.entry.implementation.join(', ')} | ${row.entry.tests.join(', ')} | ${gates} | ${row.status} |`);
  }
  lines.push('', '## Limitations', '', ...LIMITATIONS.map((item) => `- ${item}`), '');
  return lines.join('\n');
}

export function run(root: string): number {
  const map = JSON.parse(readFileSync(join(root, 'tools', 'trace-map.json'), 'utf8')) as TraceMap;
  const gates = Object.keys(JSON.parse(readFileSync(join(root, 'tools', 'gates.json'), 'utf8')) as Record<string, unknown>);
  const problems = validateMap(map, root, gates);
  if (problems.length > 0) {
    for (const problem of problems) console.error(problem);
    return 1;
  }
  const rows = buildRows(map, join(root, 'records', 'evidence'));
  const report = renderReport(rows);
  const target = join(root, 'records', 'traceability', 'AEG-TRC-001_trace-report.md');
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, report);
  for (const row of rows) console.log(`${row.requirement}: ${row.status}`);
  console.log('Limitations:');
  for (const item of LIMITATIONS) console.log(`- ${item}`);
  return 0;
}

if (process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]) {
  process.exit(run(fileURLToPath(new URL('..', import.meta.url))));
}
