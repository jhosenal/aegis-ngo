#!/usr/bin/env python3
"""Generates the Assist content review dossier (docs/99-inbox/S0013_assist-review-dossier.md) for the release hold.

For every line of every card in content/assist/*.cards.json it shows: the text shown, the source, the section heading and the text just
before the quoted passage on the SAVED page (so applicability and phase are visible, not asserted), and engineer flags. It does not decide.
Usage: python tools/assist-review-dossier.py   (run `npm run assist:hash` first or let this script call it)
Regenerate after any content change: an approval is tied to the exact content hash.
"""
import glob
import html
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INBOX = os.path.join(ROOT, 'docs', '99-inbox')
OUT = os.path.join(INBOX, 'S0013_assist-review-dossier.md')
sys.stdout.reconfigure(encoding='utf-8')


def norm(text):
    return re.sub(r'\s+', ' ', text).strip().lower()


def stripped_with_headings(raw):
    raw = re.sub(r'(?s)<(script|style|noscript).*?</\1>', '', raw)
    raw = re.sub(r'(?is)<h([1-6])[^>]*>(.*?)</h\1>', lambda m: '\n§§' + re.sub(r'<[^>]+>', ' ', m.group(2)) + '§§\n', raw)
    return html.unescape(re.sub(r'<[^>]+>', ' ', raw))


pages = {}
for path in glob.glob(os.path.join(INBOX, 'R00*.html')):
    pages[os.path.basename(path)] = norm(stripped_with_headings(open(path, encoding='utf-8', errors='replace').read()))


def locate(passage):
    p = norm(passage).rstrip('.')
    if not p:
        return None, None, None
    for name, text in pages.items():
        i = text.find(p)
        if i < 0:
            continue
        marks = list(re.finditer(r'§§(.*?)§§', text[:i]))
        heading = marks[-1].group(1).strip() if marks else None
        before = text[max(0, i - 170):i].replace('§§', '')
        return name, heading, before
    return None, None, None


def cell(text, limit):
    return (text or '-').replace('|', '/').replace('\n', ' ')[:limit]


def flags_for(card, line, source, saved):
    out = []
    country = card.get('country', 'MY')
    if line['kind'] == 'contact':
        out.append('ROUTING: check the number and the service it reaches.')
        if country == 'ID':
            out.append('Source is a regulation abstract; it does not say every area is served.')
        if country == 'SG':
            out.append('995 is the ambulance and fire line; the police line is not shown.')
        if country == 'MY':
            out.append('999 sourced as the single national line; 112 for mobile is not shown on purpose.')
    if saved is None:
        out.append('Source not saved as an HTML page (PDF or not saved): section unknown.')
    if 'Jerebu' in source['url']:
        out.append('AGE: Malaysian MOH haze leaflet dated 2008.')
    return ' '.join(out) or '-'


def content_hash():
    result = subprocess.run('npm run -s assist:hash', shell=True, capture_output=True, text=True, cwd=ROOT)
    m = re.search(r'"contentHash": "([0-9a-f]{64})"', result.stdout)
    return m.group(1) if m else 'unavailable'


lines = []
for path in sorted(glob.glob(os.path.join(ROOT, 'content', 'assist', '*.cards.json'))):
    for card in json.load(open(path, encoding='utf-8')):
        sources = {s['sourceId']: s for s in card['sources']}
        for line in card['lines']:
            source = sources[line['sourceId']]
            saved, heading, before = locate(source['passage'])
            lines.append((card, line, source, saved, heading, before))

out = []
out.append('# S0013 — Assist content review dossier (for the release hold)\n')
out.append('Generated by `tools/assist-review-dossier.py`. Prepared by the engineer for the reviewer. Supervisor hold (2026-10-14): release stays held pending review of **contextual accuracy, country-specific emergency routing and source applicability**; saved quotations alone do not establish safe guidance. This dossier gathers evidence; it decides nothing.\n')
out.append('Content hash this dossier was generated from: `%s` (from `npm run assist:hash`). If any card changes, regenerate it; an approval must carry the hash that is current when it is recorded.\n' % content_hash())
out.append('## How the hold works\n')
out.append('`records/releases/assist-release.json` is `HELD`. In a cloud build the server answers 503 until the record has status `APPROVED`, a reviewer, a date, an evidence reference and the **exact content hash**. Any change to any card changes the hash and cancels the approval. A private preview (`AEGIS_ASSIST_PREVIEW=true`) shows the content with an "under review, not approved" banner; local and test runs show the same banner.\n')
out.append('## Review questions (answer per line)\n')
out.append('1. **Context:** does the quoted sentence apply at the moment the card presents it (before, during or after the event)? Use the "source text just before the quote" column.\n2. **Applicability:** is the source an authority of the card\'s own country, and does the sentence apply to the situation, people and place the card implies?\n3. **Routing:** is the contact line the right number for the service the visitor needs in that country, and does the source limit where or how it works?\n4. **Completeness:** does leaving out neighbouring lines of the same source change the meaning or safety of what is shown?\n')
out.append('## Findings from the engineer (not decisions)\n')
out.append('1. **Phase mixing.** Card FLOOD-KL-SELANGOR-EN-01 puts preparedness items (get information, learn the warning system, keep documents safe) in the same list as during-flood actions (go to higher ground, do not drive or wade). Someone in an active flood sees the preparedness items first. The reviewer should decide whether the card must be split by phase.')
out.append('2. **Flat source pages.** Several saved pages mark list labels in text, not headings, so the section column is thin; the "source text just before the quote" column shows the nearest label.')
out.append('3. **Routing.** Malaysia: 999 is sourced; 112 is deliberately not shown (only a 2006 consultation and a fire-specific bulletin support it). Singapore: only the ambulance and fire line 995 is shown. Indonesia: the line states only the regulation (112 as the single number, organised nationally and regionally); availability by area is not on the card.')
out.append('4. **Age.** The Malaysian haze leaflet is from 2008.')
out.append('5. **Language.** English only; Indonesian ISPU wording exists in saved Indonesian sources but no card uses it.\n')
out.append('## Per-line evidence\n')
out.append('| Card | Country | Line (kind) | Text shown | Source, saved file | Section heading | Source text just before the quote | Engineer flag | Reviewer: context / country / routing / complete |')
out.append('|---|---|---|---|---|---|---|---|---|')
for card, line, source, saved, heading, before in lines:
    out.append('| %s | %s | %s (%s) | %s | %s, %s | %s | %s | %s | |' % (
        card['id'], card.get('country', 'MY'), line['id'], line['kind'], cell(line['text'], 110), cell(source['publisher'], 40),
        saved or '-', cell(heading, 70), ('...' + cell(before, 170)) if before else '-', flags_for(card, line, source, saved)))
out.append('\n## Reviewer decision\n')
out.append('To approve: set `records/releases/assist-release.json` to `APPROVED` with `reviewedBy`, `reviewedAt`, `evidenceRef` (this note or a review record) and `contentHash` equal to the hash above. A reviewer who finds a problem leaves it `HELD` and records the finding here.\n')
with open(OUT, 'w', encoding='utf-8', newline='\n') as handle:
    handle.write('\n'.join(out) + '\n')
print('lines in dossier:', len(lines), '->', os.path.relpath(OUT, ROOT))
