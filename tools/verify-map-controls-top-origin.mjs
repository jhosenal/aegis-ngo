import { chromium, expect } from '@playwright/test';
import { mkdirSync, writeFileSync } from 'node:fs';
const origin='http://127.0.0.1:8787';
const shots='records/screenshots/map-controls-top-2026-10-16';
mkdirSync(shots,{recursive:true});
const browser=await chromium.launch({headless:true});
const receipt={origin,date:'2026-10-16',mode:'actual local environment route with refresh off; no Google environment API calls',errors:[],googleEnvironmentRequests:0};
try {
  const page=await browser.newPage({viewport:{width:1920,height:1080}});
  page.on('pageerror',error=>receipt.errors.push(error.message));
  page.on('request',request=>{if(['airquality.googleapis.com','weather.googleapis.com'].includes(new URL(request.url()).hostname)) receipt.googleEnvironmentRequests++;});
  const data=await (await page.request.get(origin+'/public/environment')).json();
  expect(data.registry.pins).toBe(125);
  expect(data.status.enabled).toBe(false);
  expect(data.pins.every(pin=>pin.air===null && Object.values(pin.weather).every(value=>value===null))).toBe(true);
  await page.goto(origin);
  await expect(page.locator('.regional-map')).toHaveAttribute('data-map-provider','google',{timeout:30000});
  const toggle=page.locator('.map-layer-control').getByRole('button',{name:'Air & Weather',exact:true});
  await expect(toggle).toHaveAttribute('aria-pressed','false');
  await toggle.click();
  const info=page.locator('.environment-layer-info');
  const disclosure=page.locator('.map-top-toolbar').getByRole('button',{name:'Air & Weather information',exact:true});
  await expect(disclosure).toHaveAttribute('aria-expanded','false');
  await expect(info.locator('.environment-info-body')).toBeHidden();
  await disclosure.click();
  await expect(info.locator('.environment-info-body')).toBeVisible();
  await expect(info).toContainText('125 of 125 monitoring locations');
  const barBox=await page.locator('.map-top-toolbar').boundingBox();
  const infoBox=await info.boundingBox();
  expect(Math.abs(infoBox.y-barBox.y-barBox.height-8)).toBeLessThan(2);
  receipt.infoDirectlyBelowToolbar=true;
  await expect(page.locator('.environment-map-cluster').first()).toBeVisible();
  expect(await page.locator('.environment-map-cluster,.environment-pin').evaluateAll(nodes=>nodes.reduce((n,node)=>n+Number(node.dataset.locationCount),0))).toBe(125);
  const clusterCount=await page.locator('.environment-map-cluster,.environment-pin').count();
  await page.screenshot({path:`${shots}/actual-info-open.png`});
  await disclosure.click();
  await expect(info.locator('.environment-info-body')).toBeHidden();
  await expect(toggle).toHaveAttribute('aria-pressed','true');
  await expect(page.locator('.environment-map-cluster,.environment-pin')).toHaveCount(clusterCount);
  receipt.infoDisclosureIndependent=true;
  const toolbar=await page.locator('.map-layer-control').evaluate(node=>({scrollWidth:node.scrollWidth,width:node.clientWidth,rows:[...node.querySelectorAll('button')].map(button=>Math.round(button.getBoundingClientRect().top))}));
  expect(new Set(toolbar.rows).size).toBe(1);
  receipt.desktopToolbar=toolbar;
  receipt.googleClusterElements=await page.locator('.environment-map-cluster,.environment-pin').count();
  await page.screenshot({path:`${shots}/actual-google-layer.png`});
  // Also exercise the geographic fallback with the same real route, without manufacturing any readings.
  await page.evaluate(()=>window.gm_authFailure());
  await expect(page.locator('.regional-map')).toHaveAttribute('data-map-provider','offline');
  await page.getByRole('combobox',{name:'Region',exact:true}).selectOption('Malaysia');
  await page.locator('.offline-environment-marker').first().dispatchEvent('click');
  const chooser=page.getByRole('dialog',{name:'Air and weather locations',exact:true});
  if(await chooser.count()) await chooser.locator('.environment-location-list button').first().click();
  const popup=page.getByRole('dialog',{name:/^Air and weather:/});
  await expect(popup).toBeVisible();
  await expect(popup.getByRole('region',{name:'Air quality',exact:true})).toContainText('Not available');
  await expect(popup.getByRole('region',{name:'Current weather',exact:true})).toContainText('Not available');
  await expect(popup).toContainText('No Google alert source for this country');
  await page.screenshot({path:`${shots}/actual-popup-desktop.png`});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:`${shots}/actual-popup-mobile.png`});
  await page.keyboard.press('Escape');
  await disclosure.click();
  await expect(info.locator('.environment-info-body')).toBeVisible();
  await page.screenshot({path:`${shots}/actual-info-mobile-open.png`});
  await disclosure.click();
  await expect(info.locator('.environment-info-body')).toBeHidden();
  await expect(page.locator('.offline-environment-marker').first()).toBeAttached();
  await page.screenshot({path:`${shots}/actual-info-mobile-closed.png`});
  await toggle.click();
  await expect(page.locator('.environment-popup,.offline-environment-marker')).toHaveCount(0);
  expect(receipt.googleEnvironmentRequests).toBe(0);
  expect(receipt.errors).toEqual([]);
  receipt.registryPins=data.registry.pins;
  receipt.refreshEnabled=data.status.enabled;
  receipt.status='PASS';
} catch(error){receipt.status='FAIL';receipt.failure=error.message;process.exitCode=1;}
finally{await browser.close();writeFileSync('records/reviews/AEG-MAP-UI-005_2026-10-16_origin.json',JSON.stringify(receipt,null,2)+'\n');console.log(JSON.stringify(receipt));}
